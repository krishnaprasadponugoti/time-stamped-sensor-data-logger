/*-------------------------------------------------------------------
File    : types.h
Purpose : Custom data type definitions for improved readability
          and portability across the project.
-------------------------------------------------------------------*/

#ifndef __TYPES_H__
#define __TYPES_H__

//-----------------------------------------------------------
// 8-bit Data Types
//-----------------------------------------------------------
typedef unsigned char u8;   // Unsigned 8-bit (0 to 255)
typedef signed char   s8;   // Signed 8-bit (-128 to 127)

//-----------------------------------------------------------
// 16-bit Data Types
//-----------------------------------------------------------
typedef unsigned short int  u16; // Unsigned 16-bit
typedef signed short   int  s16; // Signed 16-bit

//-----------------------------------------------------------
// 32-bit Data Types
//-----------------------------------------------------------
typedef unsigned int  u32;  // Unsigned 32-bit
typedef signed   int  s32;  // Signed 32-bit

//-----------------------------------------------------------
// Floating Point Types
//-----------------------------------------------------------
typedef float  f32;   // 32-bit floating point
typedef double f64;   // 64-bit floating point

#endif
